import os
import re
import base64
import logging
from io import BytesIO
from typing import Literal

from dotenv import load_dotenv
from openai import OpenAI, APIConnectionError
from PIL import Image, ImageEnhance, ImageOps
from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    ValidationError,
    field_validator,
    model_validator,
)


# --------------------------------------------------
# ENVIRONMENT AND OPENROUTER CONFIGURATION
# --------------------------------------------------

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(BASE_DIR, ".env"))

OPENROUTER_API_KEY = os.getenv("OPENROUTER_API_KEY")
MODEL = os.getenv(
    "OPENROUTER_MODEL",
    "inclusionai/ling-3.2-flash:free",
)
OPENROUTER_BASE_URL = "https://openrouter.ai/api/v1"

logger = logging.getLogger(__name__)

if not OPENROUTER_API_KEY:
    raise RuntimeError(
        "OPENROUTER_API_KEY is missing. Set it in your environment "
        "or in the .env file."
    )

# Reuse one client rather than creating a new client for every image.
client = OpenAI(
    api_key=OPENROUTER_API_KEY,
    base_url=OPENROUTER_BASE_URL,
    max_retries=1,
    timeout=120.0,
)

# One initial extraction plus at most two repair attempts.
MAX_REPAIR_ATTEMPTS = 2

TIME_OF_DAY_LABELS = {
    "morning": "Morning",
    "afternoon": "Afternoon",
    "night": "Night",
}

CLOCK_TIME_PATTERN = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")


# --------------------------------------------------
# PYDANTIC EXTRACTION MODELS
# --------------------------------------------------

class MedicationExtraction(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid")

    name: str = "Unknown"
    dosage: str = ""
    frequency_per_day: int = Field(default=0, ge=0, le=24)
    times_of_day: list[str] = Field(default_factory=list)
    duration_days: int = Field(default=0, ge=0, le=365)
    instructions: str = ""
    verification_note: str = ""

    raw_transcription: str = ""
    name_confidence: Literal["high", "medium", "low"] = "low"
    dosage_confidence: Literal["high", "medium", "low"] = "low"
    frequency_confidence: Literal["high", "medium", "low"] = "low"

    @model_validator(mode="before")
    @classmethod
    def require_all_fields(cls, data):
        # A field omitted by the model is missing information, not a
        # successful extraction. Reject it so the repair loop can retry.
        if not isinstance(data, dict):
            return data

        missing = [
            field_name
            for field_name in cls.model_fields
            if field_name not in data
            # verification_note is generated by our application when
            # information is unavailable, so the model may omit it.
            and field_name != "verification_note"
        ]

        if missing:
            raise ValueError(
                "missing required medication fields: "
                + ", ".join(missing)
            )

        return data

    @field_validator("name")
    @classmethod
    def require_name(cls, value: str) -> str:
        # An unreadable name is reported as "Unknown"; it is never invented.
        return value.strip() or "Unknown"

    @field_validator("times_of_day")
    @classmethod
    def validate_times_of_day(cls, value: list[str]) -> list[str]:
        normalized = []

        for item in value:
            text = item.strip()
            label = TIME_OF_DAY_LABELS.get(text.lower())

            if label is not None:
                normalized.append(label)
            elif CLOCK_TIME_PATTERN.match(text):
                normalized.append(text)
            else:
                raise ValueError(
                    "times_of_day entries must be Morning, Afternoon, "
                    "Night or a 24-hour HH:MM time."
                )

        return normalized

    @model_validator(mode="after")
    def note_missing_information(self):
        # Record unavailable information instead of leaving it silent.
        # Only the absence of data is described; nothing is invented.
        notes = []

        if self.name == "Unknown":
            notes.append(
                "Medication name could not be read from the prescription."
            )

        if not self.dosage:
            notes.append(
                "Dosage was not visible on the prescription."
            )

        if self.frequency_per_day == 0:
            notes.append(
                "Frequency could not be determined from the prescription."
            )

        if self.duration_days == 0:
            notes.append(
                "Duration was not visible on the prescription."
            )

        if notes:
            existing = self.verification_note.strip()
            combined = " ".join(notes)
            self.verification_note = (
                f"{existing} {combined}" if existing else combined
            )

        return self


class PrescriptionExtraction(BaseModel):
    model_config = ConfigDict(strict=True, extra="forbid")

    doctor_notes: str = ""
    medications: list[MedicationExtraction] = Field(
        default_factory=list
    )


# --------------------------------------------------
# IMAGE PROCESSING
# --------------------------------------------------

def encode_image(image_bytes: bytes, mime_type: str) -> str:
    encoded = base64.b64encode(image_bytes).decode("utf-8")
    return f"data:{mime_type};base64,{encoded}"


def preprocess_image(image_bytes: bytes) -> bytes:
    """
    Create an enhanced image while preserving the original.

    Operations:
    - Correct EXIF orientation.
    - Convert to RGB.
    - Improve local readability using autocontrast.
    - Improve contrast and sharpness.
    - Resize very large images.
    """
    with Image.open(BytesIO(image_bytes)) as source:
        image = ImageOps.exif_transpose(source)
        image = image.convert("RGB")

        image = ImageOps.autocontrast(
            image,
            cutoff=1,
        )

        image = ImageEnhance.Contrast(image).enhance(1.25)
        image = ImageEnhance.Sharpness(image).enhance(1.35)

        max_dimension = 2200

        if max(image.size) > max_dimension:
            image.thumbnail(
                (max_dimension, max_dimension),
                Image.Resampling.LANCZOS,
            )

        output = BytesIO()

        image.save(
            output,
            format="JPEG",
            quality=92,
            optimize=True,
        )

        return output.getvalue()


# --------------------------------------------------
# VALIDATION AND REPAIR HELPERS
# --------------------------------------------------

def describe_validation_error(error: ValidationError) -> str:
    return "; ".join(
        f"{'.'.join(str(part) for part in item['loc']) or 'root'}: "
        f"{item['msg']}"
        for item in error.errors()
    )


def build_repair_message(error: ValidationError) -> str:
    return (
        "The previous JSON failed validation: "
        f"{describe_validation_error(error)}. "
        "Return the corrected JSON only, using exactly the same "
        "structure. Do not invent or add medication information "
        "that is not visible in the prescription. Use 0 for unknown "
        "numeric values, empty strings for unavailable text, and one "
        "of high, medium or low for confidence values."
    )


# --------------------------------------------------
# MAIN PRESCRIPTION EXTRACTION FUNCTION
# --------------------------------------------------

def parse_prescription_image(
    image_bytes: bytes,
    mime_type: str,
) -> PrescriptionExtraction:
    """
    Extract prescription information using the OpenRouter vision model.

    The function signature and returned Pydantic schema are kept
    compatible with the existing FastAPI application.
    """

    if not OPENROUTER_API_KEY:
        raise RuntimeError("OPENROUTER_API_KEY is missing.")

    if mime_type not in (
        "image/jpeg",
        "image/png",
        "image/webp",
    ):
        raise ValueError(
            "Only JPEG, PNG and WEBP images are supported."
        )

    if not image_bytes:
        raise ValueError("Uploaded image is empty.")

    try:
        enhanced_bytes = preprocess_image(image_bytes)
    except Exception as error:
        logger.exception("Prescription image preprocessing failed.")
        raise ValueError(
            "The uploaded image could not be processed."
        ) from error

    original_image_url = encode_image(
        image_bytes,
        mime_type,
    )

    enhanced_image_url = encode_image(
        enhanced_bytes,
        "image/jpeg",
    )

    instructions = """
You are an advanced medical prescription handwriting
transcription assistant.

Your task is to accurately transcribe the information
visible in the supplied prescription images.

You receive two views of the SAME prescription:
1. The original photograph.
2. An enhanced version of that photograph.

Use both views together. The original is the primary
source of truth. The enhanced version is supplementary.

CRITICAL TRANSCRIPTION PRINCIPLES:

1. Read the handwriting carefully, character by character.
2. Use visual context, handwriting patterns and nearby
   prescription information to interpret difficult text.
3. Do not require every character to be perfectly clear
   before attempting a transcription.
4. Preserve partially readable text instead of replacing
   the entire entry with "Unknown".
5. Never invent a medication or silently substitute
   a different medication.
6. Do not turn a possible interpretation into a confirmed
   medication name.
7. Extract every medication entry separately.
8. Do not omit entries because handwriting is difficult.

PARTIAL TRANSCRIPTION:

If only part of a medication name is readable:
- Put the readable transcription in name.
- Put the visible handwriting in raw_transcription.
- Mark name_confidence as "low" or "medium".
- Explain the uncertain characters in verification_note.
- Do not invent the missing characters.

If no meaningful part of the name can be read:
- Use "Unknown" for name.
- Preserve other readable fields.
- Explain why identification is uncertain.

FIELD-BY-FIELD EXTRACTION:

Medication name:
- Transcribe the visible name as accurately as possible.
- Do not replace a partially readable name with Unknown.

Dosage:
- Extract strength, units and formulation independently.
- Examples: 20 mg, 7.5 mg, 5 ml.
- Do not confuse medicine strength with administered amount.
- A readable dosage must be preserved even if the
  medication name is uncertain.

Frequency:
- Extract frequency only when supported by the handwriting.
- Use 0 when frequency cannot be determined.

Administration times:
- Use Morning, Afternoon or Night only when supported.
- Use HH:MM for explicitly written clock times.
- For clear 1-0-1 notation, use frequency 2 and
  ["Morning", "Night"].
- Do not infer schedules from ambiguous marks.

Duration:
- Extract the number of days only when visible.
- Use 0 when unknown.

Instructions:
- Preserve the doctor's written instructions.
- Do not invent missing instructions.

CONFIDENCE SCORES:

Assign a separate confidence score to each field:
- "high": clearly readable.
- "medium": mostly readable but some ambiguity exists.
- "low": substantially uncertain or partially unreadable.

Confidence must describe visual transcription certainty,
not whether a medication is medically appropriate.

VERIFICATION:

- Flag uncertain names, strengths, schedules and durations.
- Include possible readings only as explicitly unconfirmed
  possibilities in verification_note.
- Do not silently select between multiple possible readings.
- Use an empty verification_note only when the extracted
  information is sufficiently clear.
- Do not provide medical advice.

OTHER RULES:

- Extract doctor notes when visible.
- If the image is not a prescription, return no medications.
- Do not infer strength from a brand name.
- Do not calculate or modify a doctor's prescription.
- Never manufacture missing information.

OUTPUT:

Return valid JSON with exactly this structure:

{
  "doctor_notes": "",
  "medications": [
    {
      "name": "",
      "dosage": "",
      "frequency_per_day": 0,
      "times_of_day": [],
      "duration_days": 0,
      "instructions": "",
      "verification_note": "",
      "raw_transcription": "",
      "name_confidence": "low",
      "dosage_confidence": "low",
      "frequency_confidence": "low"
    }
  ]
}

All fields are required for every medication.
Use lowercase confidence values: high, medium or low.
Use empty strings for unavailable text.
Use 0 for unknown numeric values.
Return JSON only.
"""

    logger.info(
        "Starting prescription extraction using OpenRouter model %s",
        MODEL,
    )

    messages = [
        {
            "role": "system",
            "content": instructions,
        },
        {
            "role": "user",
            "content": [
                {
                    "type": "text",
                    "text": (
                        "Inspect both views of this prescription. "
                        "Transcribe every medication separately. "
                        "Preserve partial readings, extract each "
                        "field independently, and flag uncertainty."
                    ),
                },
                {
                    "type": "image_url",
                    "image_url": {
                        "url": original_image_url,
                    },
                },
                {
                    "type": "image_url",
                    "image_url": {
                        "url": enhanced_image_url,
                    },
                },
            ],
        },
    ]

    extraction = None
    last_error = None

    for attempt in range(MAX_REPAIR_ATTEMPTS + 1):
        try:
            response = client.chat.completions.create(
                model=MODEL,
                messages=messages,
                response_format={"type": "json_object"},
                temperature=0.1,
                max_tokens=5000,
            )
        except APIConnectionError as error:
            logger.exception(
                "OpenRouter connection failed on extraction attempt %s. "
                "Underlying cause: %r",
                attempt + 1,
                error.__cause__,
            )
            raise RuntimeError(
                "Could not connect to OpenRouter. Check Render outbound "
                "network/DNS/TLS connectivity and inspect the underlying "
                "cause in the server logs."
            ) from error
        except Exception:
            logger.exception(
                "OpenRouter API request failed on extraction attempt %s.",
                attempt + 1,
            )
            raise

        result = response.choices[0].message.content

        if not result:
            last_error = f"{MODEL} returned an empty response."
            logger.warning(
                "Prescription extraction attempt %s returned no content.",
                attempt + 1,
            )
            messages.append(
                {
                    "role": "user",
                    "content": (
                        "The previous response was empty. Return the JSON "
                        "object only, using exactly the documented "
                        "structure. Do not invent medication information."
                    ),
                }
            )
            continue

        try:
            extraction = PrescriptionExtraction.model_validate_json(
                result
            )
            break
        except ValidationError as error:
            last_error = error
            logger.warning(
                "Prescription extraction attempt %s failed validation: %s",
                attempt + 1,
                describe_validation_error(error),
            )
            messages.append(
                {
                    "role": "assistant",
                    "content": result,
                }
            )
            messages.append(
                {
                    "role": "user",
                    "content": build_repair_message(error),
                }
            )

    if extraction is None:
        detail = (
            describe_validation_error(last_error)
            if isinstance(last_error, ValidationError)
            else last_error
        )
        raise ValueError(
            "Prescription extraction failed validation after "
            f"{MAX_REPAIR_ATTEMPTS + 1} attempts: {detail}"
        )

    logger.info(
        "Prescription extraction completed: %s medications",
        len(extraction.medications),
    )

    return extraction
