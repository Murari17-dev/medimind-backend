@app.get("/api/v1/prescriptions")
def get_prescriptions():
    with engine.connect() as connection:
        prescriptions = connection.execute(
            text("""
                SELECT id
                FROM prescriptions
                ORDER BY id DESC
            """)
        ).fetchall()

    return [
        build_prescription_response(row.id)
        for row in prescriptions
    ]


@app.post(
    "/api/v1/parse-prescription",
    response_model=PrescriptionResponse
)
async def parse_prescription(file: UploadFile = File(...)):

    allowed_types = [
        "image/jpeg",
        "image/png",
        "image/webp"
    ]

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Only JPEG, PNG and WEBP images are supported."
        )

    image_bytes = await file.read()

    if len(image_bytes) > 10 * 1024 * 1024:
        raise HTTPException(
            status_code=413,
            detail="Image exceeds the 10 MB upload limit."
        )

    if not image_bytes:
        raise HTTPException(
            status_code=400,
            detail="Uploaded image is empty."
        )

    try:
        extraction = parse_prescription_image(
            image_bytes,
            file.content_type
        )

        prescription_id = save_prescription(extraction)

        response = build_prescription_response(prescription_id)

        return response

    except HTTPException:
        raise

    except Exception as error:
        print(f"Prescription processing error: {error}")
        raise HTTPException(
            status_code=500,
            detail="Prescription processing failed. Check backend logs."
        )
