def initialize_database():
    with engine.begin() as connection:

        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS prescriptions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                doctor_notes TEXT
            )
        """))

        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS medications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                prescription_id BIGINT REFERENCES prescriptions(id)
                    ON DELETE CASCADE,
                name VARCHAR(255),
                dosage VARCHAR(255),
                frequency_per_day INTEGER,
                times_of_day TEXT,
                duration_days INTEGER,
                instructions TEXT,
                verification_note TEXT
            )
        """))

        # Additive migrations: preserve existing records. Legacy rows remain
        # unassigned (user_id NULL) and are never exposed to new accounts.
        connection.execute(text("ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS user_id UUID"))
        connection.execute(text("ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ DEFAULT NOW()"))

        migrations = [
            "ALTER TABLE prescriptions ADD COLUMN IF NOT EXISTS user_id UUID",
            """
            ALTER TABLE medications
            ADD COLUMN IF NOT EXISTS verification_note TEXT
            """,
            """
            ALTER TABLE medications
            ADD COLUMN IF NOT EXISTS raw_transcription TEXT
            """,
            """
            ALTER TABLE medications
            ADD COLUMN IF NOT EXISTS name_confidence VARCHAR(10)
            DEFAULT 'low'
            """,
            """
            ALTER TABLE medications
            ADD COLUMN IF NOT EXISTS dosage_confidence VARCHAR(10)
            DEFAULT 'low'
            """,
            """
            ALTER TABLE medications
            ADD COLUMN IF NOT EXISTS frequency_confidence VARCHAR(10)
            DEFAULT 'low'
            """
        ]

        for migration in migrations:
            connection.execute(text(migration))


        # Medication reminders and durable delivery claims.
        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS medication_reminders (
                id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                user_id UUID NOT NULL,
                prescription_id BIGINT NULL REFERENCES prescriptions(id) ON DELETE SET NULL,
                medication_name VARCHAR(255) NOT NULL,
                dosage VARCHAR(255) NOT NULL DEFAULT '',
                instructions TEXT NOT NULL DEFAULT '',
                reminder_time TIME NOT NULL,
                start_date DATE NOT NULL,
                end_date DATE NOT NULL,
                timezone VARCHAR(100) NOT NULL DEFAULT 'Asia/Kolkata',
                enabled BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                CONSTRAINT medication_reminders_valid_dates
                    CHECK (end_date >= start_date)
            )
        """))
        connection.execute(text("""
            CREATE INDEX IF NOT EXISTS idx_medication_reminders_user
            ON medication_reminders (user_id, enabled)
        """))
        connection.execute(text("""
            CREATE TABLE IF NOT EXISTS reminder_deliveries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reminder_id UUID NOT NULL REFERENCES medication_reminders(id)
                    ON DELETE CASCADE,
                scheduled_for TIMESTAMPTZ NOT NULL,
                claim_token UUID,
                lease_expires_at TIMESTAMPTZ,
                delivered_at TIMESTAMPTZ,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (reminder_id, scheduled_for)
            )
        """))
        connection.execute(text("""
            ALTER TABLE reminder_deliveries
            ADD COLUMN IF NOT EXISTS claim_token UUID
        """))
        connection.execute(text("""
            ALTER TABLE reminder_deliveries
            ADD COLUMN IF NOT EXISTS lease_expires_at TIMESTAMPTZ
        """))
        connection.execute(text("""
            ALTER TABLE reminder_deliveries
            ALTER COLUMN delivered_at DROP NOT NULL
        """))
        connection.execute(text("""
            ALTER TABLE reminder_deliveries
            ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        """))

    logger.info("Database initialization completed.")


initialize_database()


