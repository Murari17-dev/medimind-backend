@app.delete("/api/v1/prescriptions/{prescription_id}")
def delete_prescription(
    prescription_id: int,
    current_user: dict = Depends(get_current_user),
):
    # The owner check is part of the DELETE itself. A prescription belonging
    # to another account is indistinguishable from a nonexistent prescription.
    with engine.begin() as connection:
        deleted = connection.execute(
            text("""
                DELETE FROM prescriptions
                WHERE id = :prescription_id
                  AND user_id = CAST(:user_id AS UUID)
                RETURNING id
            """),
            {
                "prescription_id": prescription_id,
                "user_id": current_user["id"],
            },
        ).scalar_one_or_none()

    if deleted is None:
        raise HTTPException(status_code=404, detail="Prescription not found.")

    # Existing FK rules cascade-delete its medications and set linked
    # medication_reminders.prescription_id to NULL, preserving those reminders.
    return {
        "deleted": True,
        "prescription_id": deleted,
    }


@app.delete("/api/v1/prescriptions")
def delete_all_prescriptions(current_user: dict = Depends(get_current_user)):
    # Only rows owned by the authenticated user are selected for deletion.
    # Legacy rows with user_id NULL and every other user's rows remain untouched.
    with engine.begin() as connection:
        deleted_ids = connection.execute(
            text("""
                DELETE FROM prescriptions
                WHERE user_id = CAST(:user_id AS UUID)
                RETURNING id
            """),
            {"user_id": current_user["id"]},
        ).scalars().all()

    return {
        "deleted": True,
        "deleted_count": len(deleted_ids),
    }


@app.post(
    "/api/v1/parse-prescription",
    response_model=PrescriptionResponse
)
async def parse_prescription(
    file: UploadFile = File(...),
    current_user: dict = Depends(get_current_user),
):

    allowed_types = {
        "image/jpeg",
        "image/png",
        "image/webp"
    }

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Only JPEG, PNG and WEBP images are supported."
        )

    try:
        image_bytes = await file.read(MAX_UPLOAD_BYTES + 1)

        if len(image_bytes) > MAX_UPLOAD_BYTES:
            raise HTTPException(
                status_code=413,
                detail="Image exceeds the 10 MB upload limit."
            )

        if not image_bytes:
            raise HTTPException(
                status_code=400,
                detail="Uploaded image is empty."
            )

        logger.info(
            "Prescription received: filename=%s size=%s content_type=%s",
            file.filename,
            len(image_bytes),
            file.content_type
        )

        # Run synchronous AI processing outside the event loop.
        extraction = await run_in_threadpool(
            parse_prescription_image,
            image_bytes,
            file.content_type
        )

        prescription_id = save_prescription(extraction, current_user["id"])

        result = build_prescription_response(prescription_id, current_user["id"])

        logger.info(
            "Prescription saved successfully: id=%s medications=%s",
            prescription_id,
            len(extraction.medications)
        )

        return result

    except HTTPException:
        raise

    except ValueError as error:
        logger.warning(
            "Prescription image or extraction validation failed: %s",
            error
        )

        raise HTTPException(
            status_code=422,
            detail=str(error)
        )

    except Exception:
        logger.exception("Prescription processing failed.")

        raise HTTPException(
            status_code=500,
            detail=(
                "Prescription processing failed. "
                "Please try again later."
            )
        )

    finally:
        await file.close()
