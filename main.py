def decode_times(value):
    if not value:
        return []

    try:
        decoded = json.loads(value)
        if isinstance(decoded, list):
            return decoded
    except (json.JSONDecodeError, TypeError):
        pass

    return [item.strip() for item in value.split(",") if item.strip()]


def save_prescription(extraction):
    with engine.begin() as connection:

        result = connection.execute(
            text("""
                INSERT INTO prescriptions (doctor_notes)
                VALUES (:doctor_notes)
                RETURNING id
            """),
            {"doctor_notes": extraction.doctor_notes}
        )

        prescription_id = result.scalar_one()

        for medication in extraction.medications:
            connection.execute(
                text("""
                    INSERT INTO medications (
                        prescription_id,
                        name,
                        dosage,
                        frequency_per_day,
                        times_of_day,
                        duration_days,
                        instructions,
                        verification_note
                    )
                    VALUES (
                        :prescription_id,
                        :name,
                        :dosage,
                        :frequency_per_day,
                        :times_of_day,
                        :duration_days,
                        :instructions,
                        :verification_note
                    )
                """),
                {
                    "prescription_id": prescription_id,
                    "name": medication.name,
                    "dosage": medication.dosage,
                    "frequency_per_day": medication.frequency_per_day,
                    "times_of_day": json.dumps(medication.times_of_day),
                    "duration_days": medication.duration_days,
                    "instructions": medication.instructions,
                    "verification_note": medication.verification_note,
                }
            )

    return prescription_id


def build_prescription_response(prescription_id):
    with engine.connect() as connection:

        prescription = connection.execute(
            text("""
                SELECT id, doctor_notes
                FROM prescriptions
                WHERE id = :id
            """),
            {"id": prescription_id}
        ).mappings().first()

        if not prescription:
            return None

        medications = connection.execute(
            text("""
                SELECT
                    name,
                    dosage,
                    instructions,
                    times_of_day,
                    frequency_per_day,
                    duration_days,
                    verification_note
                FROM medications
                WHERE prescription_id = :prescription_id
                ORDER BY id
            """),
            {"prescription_id": prescription_id}
        ).mappings().all()

        return PrescriptionResponse(
            id=prescription["id"],
            doctor_notes=prescription["doctor_notes"],
            medications=[
                MedicationResponse(
                    name=medication["name"] or "",
                    dosage=medication["dosage"] or "",
                    instructions=medication["instructions"] or "",
                    times_of_day=decode_times(medication["times_of_day"]),
                    frequency_per_day=medication["frequency_per_day"],
                    duration_days=medication["duration_days"],
                    verification_note=medication["verification_note"],
                )
                for medication in medications
            ]
        )


