@app.get("/api/v1/prescriptions")
def get_prescriptions(current_user: dict = Depends(get_current_user)):

    with engine.connect() as connection:

        prescriptions = connection.execute(
            text("""
                SELECT id
                FROM prescriptions
                WHERE user_id = CAST(:user_id AS UUID)
                ORDER BY created_at DESC, id DESC
            """),
            {"user_id": current_user["id"]}
        ).fetchall()

    return [
        build_prescription_response(row.id, current_user["id"])
        for row in prescriptions
    ]


@app.post(
    "/api/v1/parse-prescription",
    response_model=PrescriptionResponse
)
async def parse_prescription(
    file: UploadFile = File(...),
    current_user: dict = Depends(get_current_user),
):

    allowed_types = {
        "image/jpeg",
        "image/png",
        "image/webp"
    }

    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=400,
            detail="Only JPEG, PNG and WEBP images are supported."
        )

    try:
        image_bytes = await file.read(MAX_UPLOAD_BYTES + 1)

        if len(image_bytes) > MAX_UPLOAD_BYTES:
            raise HTTPException(
                status_code=413,
                detail="Image exceeds the 10 MB upload limit."
            )

        if not image_bytes:
            raise HTTPException(
                status_code=400,
                detail="Uploaded image is empty."
            )

        logger.info(
            "Prescription received: filename=%s size=%s content_type=%s",
            file.filename,
            len(image_bytes),
            file.content_type
        )

        # Run synchronous AI processing outside the event loop.
        extraction = await run_in_threadpool(
            parse_prescription_image,
            image_bytes,
            file.content_type
        )

        prescription_id = save_prescription(extraction, current_user["id"])

        result = build_prescription_response(prescription_id, current_user["id"])

        logger.info(
            "Prescription saved successfully: id=%s medications=%s",
            prescription_id,
            len(extraction.medications)
        )

        return result

    except HTTPException:
        raise

    except ValueError as error:
        logger.warning(
            "Prescription image or extraction validation failed: %s",
            error
        )

        raise HTTPException(
            status_code=422,
            detail=str(error)
        )

    except Exception:
        logger.exception("Prescription processing failed.")

        raise HTTPException(
            status_code=500,
            detail=(
                "Prescription processing failed. "
                "Please try again later."
            )
        )

    finally:
        await file.close()

